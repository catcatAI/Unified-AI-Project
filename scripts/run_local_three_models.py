"""Start/stop three local llama.cpp servers for the three stage roles.

Why an overlay instead of editing llm.user.yaml: the tiered loader reads
default → user → evolved, so a *generated* `llm.evolved.yaml` can turn the three
slots on for a local session and be removed afterwards without touching the
user's hand-written overrides.

Usage:
    python scripts/run_local_three_models.py start
    python scripts/run_local_three_models.py status
    python scripts/run_local_three_models.py stop
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import shutil
import signal
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional, Sequence

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import plan_local_three_models as planner  # noqa: E402

CONFIG_DIR = REPO_ROOT / "apps" / "backend" / "configs" / "system"
OVERLAY = CONFIG_DIR / "llm.evolved.yaml"
OVERLAY_BACKUP = CONFIG_DIR / "llm.evolved.yaml.pre-local"
LOGDIR = REPO_ROOT / "logs" / "local_models"
# logs/ is already ignored by git; the pidfile belongs next to the server logs.
PIDFILE = LOGDIR / "servers.pids"


def overlay_yaml(picks: Sequence[Dict[str, object]]) -> str:
    """The evolved-layer config that enables the three slots.

    Deliberately does NOT touch deployment.mode: config hygiene treats cloud
    access as a human decision, and the evolved layer must not flip it
    (scripts/check_default_config.py enforces this).
    """
    lines = [
        "# GENERATED by scripts/run_local_three_models.py — do not edit by hand.",
        "# Remove with `python scripts/run_local_three_models.py stop`.",
        "settings:",
        "  preferred_backend: llamacpp-local",
        "backends:",
    ]
    for pick in picks:
        lines.extend(
            [
                f"  {pick['slot']}:",
                "    enabled: true",
                f"    base_url: http://127.0.0.1:{pick['port']}",
                f"    model_name: {Path(str(pick['path'])).name}",
                "    context_window: 2048",
                "    timeout: 180",
            ]
        )
    return "\n".join(lines) + "\n"


def install_overlay(picks: Sequence[Dict[str, object]]) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    if OVERLAY.exists() and not OVERLAY_BACKUP.exists():
        shutil.copy2(OVERLAY, OVERLAY_BACKUP)
    OVERLAY.write_text(overlay_yaml(picks), encoding="utf-8")


def remove_overlay() -> None:
    # Only touch a file we generated. The repo ships a real llm.evolved.yaml
    # (ConfigMutator's output); deleting that on `stop` loses committed config.
    if not overlay_state().startswith("generated"):
        return
    if OVERLAY_BACKUP.exists():
        shutil.move(str(OVERLAY_BACKUP), str(OVERLAY))
    elif OVERLAY.exists():
        OVERLAY.unlink()


def healthy(port: int, timeout: float = 1.5) -> bool:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=timeout) as resp:
            return resp.status == 200
    except (urllib.error.URLError, OSError, ValueError):
        return False


def wait_healthy(port: int, seconds: float = 90.0) -> bool:
    deadline = time.time() + seconds
    while time.time() < deadline:
        if healthy(port):
            return True
        time.sleep(1.0)
    return False


def start(threads: int = 6, ctx: int = 2048) -> int:
    plan = planner.plan_three(planner.detect_vram_gb(), planner.detect_ram_gb(), ctx=ctx)
    if plan.mode == "on_demand":
        print("This machine cannot hold three models at once:")
        print(planner.render(plan))
        print("\nRefusing to start three servers — run them one at a time instead.")
        return 2

    missing = planner.check_files(plan)
    if missing:
        print("Missing model files:")
        for path in missing:
            print(f"  - {path}")
        print("\nDownload the Q4 files listed by `python scripts/plan_local_three_models.py`,")
        print(f"put them in {planner.MODELS_DIR}, then re-run this command.")
        return 3

    if not planner.SERVER_BIN.exists():
        print(f"llama-server not found at {planner.SERVER_BIN}")
        return 4

    LOGDIR.mkdir(parents=True, exist_ok=True)
    PIDFILE.parent.mkdir(parents=True, exist_ok=True)
    pids: List[int] = []
    for (placement, _model), command in zip(plan.picks, plan.commands(threads)):
        log = open(LOGDIR / f"{placement['slot']}.log", "ab")
        proc = subprocess.Popen(shlex.split(command), stdout=log, stderr=subprocess.STDOUT)
        pids.append(proc.pid)
        print(f"started {placement['slot']} (pid {proc.pid}) on port {placement['port']}")

    PIDFILE.write_text("\n".join(str(pid) for pid in pids) + "\n", encoding="utf-8")
    install_overlay(plan.to_dict()["picks"])

    ok = True
    for placement, _model in plan.picks:
        if wait_healthy(int(placement["port"])):
            print(f"  {placement['slot']} healthy on :{placement['port']}")
        else:
            ok = False
            print(f"  {placement['slot']} NOT healthy on :{placement['port']} (see {LOGDIR})")
    print(f"\nconfig overlay: {OVERLAY}")
    print("restart the backend so it picks the overlay up, then roles bind to their slots.")
    return 0 if ok else 1


def stop() -> int:
    stopped = 0
    if PIDFILE.exists():
        for raw in PIDFILE.read_text().split():
            try:
                os.kill(int(raw), signal.SIGTERM)
                stopped += 1
            except (ProcessLookupError, ValueError):
                continue
        PIDFILE.unlink()
    remove_overlay()
    print(f"stopped {stopped} server(s); overlay removed")
    return 0


def overlay_state() -> str:
    """Distinguish our generated overlay from a pre-existing hand-written one."""
    if not OVERLAY.exists():
        return "absent"
    try:
        first = OVERLAY.read_text(encoding="utf-8").splitlines()[:1]
    except OSError:
        return "unreadable"
    if first and "GENERATED by scripts/run_local_three_models" in first[0]:
        return "generated (three local models)"
    return "present (not ours — stop will not touch it)"


def status() -> int:
    plan = planner.plan_three(planner.detect_vram_gb(), planner.detect_ram_gb())
    for pick in plan.to_dict()["picks"]:
        state = "healthy" if healthy(int(pick["port"])) else "down"
        print(f"{pick['slot']:16} :{pick['port']} {state}  {pick['label']}")
    print(f"overlay: {overlay_state()}")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "action", choices=["start", "stop", "status", "plan"], nargs="?", default="plan"
    )
    parser.add_argument("--threads", type=int, default=6)
    parser.add_argument("--ctx", type=int, default=2048)
    args = parser.parse_args(argv)

    if args.action == "start":
        return start(args.threads, args.ctx)
    if args.action == "stop":
        return stop()
    if args.action == "status":
        return status()
    print(planner.render(planner.plan_three(planner.detect_vram_gb(), planner.detect_ram_gb())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
