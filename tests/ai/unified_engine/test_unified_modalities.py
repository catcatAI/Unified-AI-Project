"""
Unified Engine multimodal + language tests — the AI claims per modality.

Verifies that ONE fixed-size core learns language, image, and audio from
their raw byte streams, and GENERALISES to unseen data (never memorises):

  - fixed_memory      : model_bytes constant across every modality
  - image             : unseen image TYPE is distinguishable (lower prob
                        than seen types); generated bytes follow the PNG
                        structure
  - audio             : unseen FREQUENCY is distinguishable; learned
                        frequencies have higher probability
  - language          : held-out alpaca output has far lower perplexity
                        than random (the model really compresses language)
  - compression       : corpus_bytes / model_bytes > 1 on real data

These tests measure the RIGHT thing: generalisation on held-out samples,
exactly what the old three_axis/ED3N/GARDEN evaluations did NOT do.
"""

