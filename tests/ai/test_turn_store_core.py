# ANGELA-MATRIX: L3 [βγδ] [B] [L2]
"""§55 stage T's contract: the store arm's start, ablation and wiring.

These tests do not measure the model. They pin the things that would make a
stage-T result unreadable if they were wrong:

* the state really is ``h`` plus a store, and ``turnstore`` is a registered
  model kind (otherwise a state could not be created or attached);
* the start is L: with an empty store the logits are L's, bit for bit, and the
  first write is what makes them differ - so "the store did something" is
  observable rather than assumed;
* ``memory=False`` keeps every parameter and is *functionally* the GRU arm on
  the same start, which is what makes T2's gap attributable to the store;
* ``al_step`` leaves the store alone and matches the GRU's ``h`` exactly;
* ``start_is_stage_l`` accepts the turnstore derivation of L and rejects a
  forged provenance;
* the pair verdict (T1-T4) is computed from recorded numbers and refuses arms
  that are not the registered pair;
* the CLI refuses combinations that would silently change the arm.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SCRIPT = REPO_ROOT / "scripts" / "train_pantry_deduction.py"


@pytest.fixture(scope="module")
def stage():
    spec = importlib.util.spec_from_file_location("pantry_deduction_turnstore", SCRIPT)
    loaded = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = loaded
    spec.loader.exec_module(loaded)
    return loaded


@pytest.fixture(scope="module")
def torch():
    return pytest.importorskip("torch")


def _stage_l_path(stage):
    path = REPO_ROOT / stage.L_CHECKPOINT
    if not path.exists():
        pytest.skip("the stage-L checkpoint is a gitignored artifact")
    return path


def _pair(stage, *, hidden=128, emb=64, memory=True, seed=20261118):
    """A GRU carrier loaded from L and a store arm derived from the same file."""
    from ai.core.stateful_decoder import GRUCore, TurnStoreCore

    path = _stage_l_path(stage)
    gru = GRUCore(259, hidden=hidden, emb=emb, chunk_seconds=60.0, seed=seed, device="cpu")
    assert stage.load_stage_l(gru, path) == stage.L_WEIGHTS_HASH
    store = TurnStoreCore(
        259,
        hidden=hidden,
        emb=emb,
        chunk_seconds=60.0,
        seed=seed,
        device="cpu",
        memory=memory,
    )
    digest = stage.start_from_stage_l(store, path, source_hidden=hidden)
    return gru, store, digest


def test_turnstore_is_a_registered_model_kind(torch):
    from ai.core.core_state import MODEL_KINDS
    from ai.core.stateful_decoder import TurnStoreCore

    assert "turnstore" in MODEL_KINDS
    core = TurnStoreCore(259, hidden=8, emb=4, chunk_seconds=60.0, seed=3, device="cpu")
    state = core.init_state(2)
    assert state.model_kind == "turnstore"
    assert {name: tuple(value.shape) for name, value in state.tensors.items()} == {
        "h": (2, 8),
        "k": (2, 16, 64),
        "v": (2, 16, 64),
    }
    assert core.config()["slots"] == 16
    assert core.config()["memory"] is True


def test_start_from_stage_l_is_behaviourally_l_until_the_first_write(stage, torch):
    gru, store, digest = _pair(stage)
    assert digest != stage.L_WEIGHTS_HASH
    assert store.parameter_count() > stage.L_PARAMS

    tokens = torch.as_tensor([[11, 12, 13, 14], [21, 22, 23, 24]], dtype=torch.long)
    gru_logits, _ = gru.ai_step(tokens, gru.init_state(2))
    store_logits, store_state = store.ai_step(tokens, store.init_state(2))
    # an empty store reads 0, so head([h, 0]) is L's head(h)
    assert torch.allclose(gru_logits, store_logits, atol=1e-6)

    # one write makes the read non-zero; the *output* only changes once the
    # head's read columns are trained, which is why the start is exactly L's
    store_state.tensors = store.end_turn(store_state.tensors)
    assert int(torch.count_nonzero(store_state.tensors["k"])) > 0
    assert int(torch.count_nonzero(store.read_vector(store_state.tensors))) > 0
    assert torch.count_nonzero(store.head.weight[:, gru.hidden :]) == 0
    assert torch.equal(store.head.weight[:, : gru.hidden], gru.head.weight)


def test_ablation_keeps_every_parameter_and_is_functionally_the_gru(stage, torch):
    gru, store, _ = _pair(stage, memory=False)
    assert store.parameter_count() == _pair(stage, memory=True)[1].parameter_count()

    # identical tokens, identical gaps: the ablation must reproduce the GRU's
    # logits and its generated bytes, not merely be close
    turns = [[[3 + i, 4 + i, 5 + i] for i in range(3)]]
    gaps = [[120.0, 60.0, 240.0]]
    gru_state, gru_hidden = stage.run_session(gru, turns, gaps)
    store_state, store_hidden = stage.run_session(store, turns, gaps)
    assert torch.equal(gru_hidden, store_state.tensors["h"])
    assert torch.equal(store_state.tensors["k"], torch.zeros_like(store_state.tensors["k"]))
    assert stage.generate_bytes(gru, gru_hidden) == stage.generate_bytes(
        store, dict(store_state.tensors)
    )


def test_end_turn_is_the_only_write_and_memory_false_never_writes(stage, torch):
    _, store, _ = _pair(stage, memory=False)
    state = store.init_state(1)
    tokens = torch.as_tensor([[40, 41, 42]], dtype=torch.long)
    state.tensors = store.consume(tokens[:, 0], state.tensors)
    before = {name: value.clone() for name, value in state.tensors.items()}
    state.tensors = store.end_turn(state.tensors)
    assert torch.equal(state.tensors["h"], before["h"])
    assert torch.equal(state.tensors["k"], before["k"])
    assert torch.equal(state.tensors["v"], before["v"])


def test_al_step_matches_the_gru_and_leaves_the_store_alone(stage, torch):
    gru, store, _ = _pair(stage)
    gru_state = gru.init_state(2)
    store_state = store.init_state(2)
    tokens = torch.as_tensor([[7, 8], [9, 10]], dtype=torch.long)
    gru_state.tensors["h"] = gru.consume(tokens[:, 0], gru_state.tensors)["h"]
    store_state.tensors = store.consume(tokens[:, 0], store_state.tensors)
    store_state.tensors = store.end_turn(store_state.tensors)
    keys_before = store_state.tensors["k"].clone()

    gru.al_step([180.0, 30.0], gru_state)
    store.al_step([180.0, 30.0], store_state)
    assert torch.allclose(gru_state.tensors["h"], store_state.tensors["h"], atol=1e-6)
    assert torch.equal(store_state.tensors["k"], keys_before)
    assert store_state.ticks == gru_state.ticks


def test_turn_boundaries_are_snapshots_not_views_of_the_live_store(stage, torch):
    """An earlier boundary must not see later turns' writes (aux-loss leakage)."""
    _, store, _ = _pair(stage)
    short = [[[3 + i, 4 + i] for i in range(3)]]
    long = [[[3 + i, 4 + i] for i in range(3)] + [[60, 61, 62]]]
    gaps = [[120.0, 60.0, 240.0]]
    early: list = []
    stage.run_session(store, short, gaps, boundaries=early)
    late: list = []
    stage.run_session(store, long, [[120.0, 60.0, 240.0, 90.0]], boundaries=late)

    before = early[1]
    after = late[1]
    assert isinstance(before, dict) and set(before) == {"h", "k", "v"}
    for name in ("h", "k", "v"):
        assert torch.equal(before[name], after[name])
    # and the later turn did write, so the equality is not because nothing happens
    assert not torch.equal(late[2]["k"], before["k"])


def test_start_predicate_accepts_the_derivation_and_rejects_a_forgery(stage):
    derived = {
        "checkpoint": stage.L_CHECKPOINT,
        "checkpoint_sha256": stage.L_CHECKPOINT_SHA256,
        "weights_hash": "sha256:" + "0" * 64,
        "params": stage.L_PARAMS + 43_539,
        "derived_from": "turnstore",
        "source_weights_hash": stage.L_WEIGHTS_HASH,
        "hidden": 128,
    }
    assert stage.start_is_stage_l(derived)
    for broken in (
        {**derived, "source_weights_hash": "sha256:" + "f" * 64},
        {**derived, "hidden": 64},
        {**derived, "params": stage.L_PARAMS},
        {**derived, "checkpoint_sha256": "0" * 64},
    ):
        assert not stage.start_is_stage_l(broken)


def _t_report(stage, *, memory, exact, digest="train", seed=20261118, epochs=400):
    return {
        "config": {
            "core": "turnstore",
            "memory": memory,
            "gate_prefix": "T",
            "seed": seed,
            "lr": 5e-4,
            "batch": 8,
            "epochs": epochs,
            "token_count": 259,
            "hidden": 128,
            "emb": 64,
        },
        "overfit": True,
        "corpus": {"train_digest": digest},
        "start": {"source_weights_hash": stage.L_WEIGHTS_HASH},
        "results": {"train_fit": {"exact": exact}},
        "cost": {"params": 168_150, "train_seconds": 300.0, "device": "cpu"},
    }


def test_stage_t_pair_verdict_is_computed_and_the_branch_is_mechanical(stage):
    passing = stage.stage_t_comparison(
        _t_report(stage, memory=True, exact=0.9375),
        _t_report(stage, memory=False, exact=0.375),
    )
    assert passing["all_pass"] is True
    assert passing["gap"] == 0.5625
    assert "T1+T2 pass" in passing["branch"]

    short = stage.stage_t_comparison(
        _t_report(stage, memory=True, exact=0.7188),
        _t_report(stage, memory=False, exact=0.375),
    )
    assert short["checks"]["T1_store_fits_at_budget"] is False
    assert short["checks"]["T2_store_minus_ablation"] is True
    assert short["checks"]["T3_ablation_matches_gru"] is True
    assert "T1 fails but T2 passes" in short["branch"]

    wrong_ablation = stage.stage_t_comparison(
        _t_report(stage, memory=True, exact=0.9375),
        _t_report(stage, memory=False, exact=0.75),
    )
    assert wrong_ablation["checks"]["T3_ablation_matches_gru"] is False
    assert "T3 fails" in wrong_ablation["branch"]

    with pytest.raises(SystemExit):
        stage.stage_t_comparison(
            _t_report(stage, memory=True, exact=0.9375),
            _t_report(stage, memory=False, exact=0.375, digest="other"),
        )
    with pytest.raises(SystemExit):
        stage.stage_t_comparison(
            _t_report(stage, memory=True, exact=0.9375),
            _t_report(stage, memory=True, exact=0.375),
        )


def test_stage_t_single_report_cannot_claim_the_pair(stage):
    """T2 needs both arms, so it is None on a single report (never a silent pass)."""
    gates = stage.gate_values(_t_report(stage, memory=True, exact=0.9375))
    assert gates["T1_store_fits_at_budget"] is True
    assert gates["T2_store_minus_ablation"] is None
    assert gates["T3_ablation_matches_gru"] is None
    assert gates["T4_cost_recorded"] is True
    assert stage.verdict(gates) is True

    ablation = stage.gate_values(_t_report(stage, memory=False, exact=0.375))
    assert ablation["T1_store_fits_at_budget"] is None
    assert ablation["T3_ablation_matches_gru"] is True


def test_cli_refuses_combinations_that_change_the_arm(stage):
    for argv in (
        ["--overfit", "1", "--no-memory"],
        ["--overfit", "1", "--core", "turnstore", "--widen-to", "256"],
        ["--overfit", "1", "--core", "turnstore", "--hidden", "64"],
        ["--overfit", "1", "--core", "turnstore", "--emb", "32"],
        ["--overfit", "1", "--core", "nope"],
    ):
        with pytest.raises(SystemExit):
            stage.main(argv)
